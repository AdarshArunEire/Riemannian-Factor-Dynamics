"""E4 -- BW barycentre cost model, and whether N-19's budget survives it.

A MEASUREMENT, not a falsifier: no assertions, no pass/fail, nothing here
can confirm or refute a claim. It exists to answer one question before any
result is seen --

    is the predeclared N-19 budget (20 streams x 50,000 draws, 18 cells)
    affordable with this implementation?

Run it BEFORE N-19. If the answer is no, the budget gets amended on
timing evidence alone, which keeps the amendment outcome-independent. Find
out afterwards and the amendment is contaminated by having seen results.

    python experiments/e4_bw_cost.py

Takes about a minute. Writes results/final/bw_cost_model.md (the record)
and results/final/bw_cost_model.csv (the same numbers, for plotting).
"""

import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "py"))

from rfd.dgp.spd import random_spd
from rfd.spd.bw import bw_barycentre

SEED = 20260816
MS = [3, 12]
NS = [100, 1000, 10000, 50000]
CONDS = [1e1, 1e3]
TOL = 1e-12
OUT = "results/final/bw_cost_model.md"
OUT_CSV = "results/final/bw_cost_model.csv"

# N-19 as predeclared in config/predeclaration.yaml
N19_STREAMS = 20
N19_DRAWS = 50000
N19_M = [3, 12]
N19_MVALS = [21, 78, 1638]      # M, the proxy averaging window
N19_SPECTRA = 3
N19_CELLS_PER_M = len(N19_MVALS) * N19_SPECTRA      # 9


def timed_barycentre(m, n, cond):
    """One full run. Returns (seconds, n_iter, converged)."""
    rng = np.random.default_rng(SEED)
    S = random_spd(rng, m=m, cond=cond, n=n)
    t0 = time.perf_counter()
    res = bw_barycentre(S, tol=TOL)
    return time.perf_counter() - t0, res.n_iter, res.converged


def thread_info():
    try:
        from threadpoolctl import threadpool_info

        return ", ".join(
            f"{d.get('internal_api', '?')}={d.get('num_threads', '?')}"
            for d in threadpool_info()
        ) or "none reported"
    except Exception:
        return "threadpoolctl not installed -- thread count unknown"


def main():
    # warmup: first BLAS call pays for initialisation, don't charge it to a cell
    timed_barycentre(3, 100, 10.0)

    rows = []
    for m in MS:
        for cond in CONDS:
            for n in NS:
                secs, iters, ok = timed_barycentre(m, n, cond)
                per_iter = secs / iters
                rows.append((m, cond, n, secs, iters, per_iter, ok))
                print(
                    f"  m={m:<3d} cond={cond:<7.0e} N={n:<6d} "
                    f"{secs:7.3f}s  {iters:3d} iters  {per_iter * 1e3:8.2f} ms/iter"
                    f"{'' if ok else '   NOT CONVERGED'}",
                    flush=True,
                )

    # projection: worst cond measured, at the declared draw count
    at50k = {
        m: max(r[3] for r in rows if r[0] == m and r[2] == N19_DRAWS) for m in MS
    }
    total_s = sum(N19_CELLS_PER_M * N19_STREAMS * at50k[m] for m in N19_M)

    # draw-stage memory: one (m, M) normal matrix per draw, held in a chunk
    mem = {
        (m, M): m * M * 8 / 1e6 for m in N19_M for M in N19_MVALS
    }  # MB per 1000 draws = this * 1000 / 1000

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    L = [
        "# E4 -- BW barycentre cost model",
        "",
        "Generated by `experiments/e4_bw_cost.py`. Measurement only: no",
        "assertions, no pass/fail. Re-run and append a dated section rather",
        "than editing.",
        "",
        f"- generated: {stamp}",
        f"- seed: {SEED}, tol: {TOL:.0e}",
        f"- numpy {np.__version__}, python {platform.python_version()}",
        f"- machine: {platform.processor() or 'unknown'} / {platform.platform()}",
        f"- BLAS threads: {thread_info()}",
        "",
        "## Measured",
        "",
        "| m | cond | N | seconds | iters | ms/iter | converged |",
        "|---|---|---|---|---|---|---|",
    ]
    for m, cond, n, secs, iters, per_iter, ok in rows:
        L.append(
            f"| {m} | {cond:.0e} | {n} | {secs:.3f} | {iters} | "
            f"{per_iter * 1e3:.2f} | {ok} |"
        )

    L += [
        "",
        "Read the ms/iter column ACROSS N at fixed (m, cond): it should be",
        "roughly linear in N. If it is superlinear, something is allocating",
        "per draw and the batching is not doing what it looks like it is.",
        "",
        "Read the iters column across N: expect FLAT or mildly DECREASING.",
        "Iteration count is set by how far apart the inputs are, not by how",
        "many there are. A mild decrease with N is benign and expected --",
        "averaging more draws concentrates the arithmetic mean, so the",
        "initialisation starts closer to the answer. An INCREASE with N would",
        "not be benign: it would mean the dispersion of `random_spd` grows",
        "with n, which would confound E1's dispersion knob entirely.",
        "",
        "## Projection to N-19 as predeclared",
        "",
        f"- {N19_STREAMS} streams x {N19_DRAWS} draws",
        f"- m in {N19_M}, M in {N19_MVALS}, {N19_SPECTRA} spectra"
        f" -> {N19_CELLS_PER_M} cells per m",
        "",
        "| m | worst measured barycentre at N=50000 | x cells x streams |",
        "|---|---|---|",
    ]
    for m in N19_M:
        L.append(
            f"| {m} | {at50k[m]:.2f} s | "
            f"{N19_CELLS_PER_M * N19_STREAMS * at50k[m] / 60:.1f} min |"
        )
    L += [
        "",
        f"**Projected BW-barycentre time for the full N-19 grid: "
        f"{total_s / 60:.1f} minutes ({total_s / 3600:.2f} h).**",
        "",
        "## What this number does NOT include",
        "",
        "Stated explicitly because a cost model that quietly omits terms is",
        "worse than no cost model:",
        "",
        "- proxy generation (Wishart draws). Not written yet.",
        "- the AIRM barycentre (B1.3, not implemented). Karcher mean is",
        "  gradient descent and is typically SLOWER per iteration than the AE",
        "  fixed point -- assume this roughly doubles the total, at least.",
        "- the Frobenius barycentre, which is a mean and is free.",
        "- C5's non-Wishart proxy, which needs its own generator.",
        "",
        "## Draw-stage memory",
        "",
        "A Wishart draw at averaging window M needs an (m, M) normal matrix.",
        "Held for a chunk of 1000 draws:",
        "",
        "| m | M | MB per 1000 draws |",
        "|---|---|---|",
    ]
    for (m, M), mb in mem.items():
        L.append(f"| {m} | {M} | {mb * 1000:.0f} |")
    L += [
        "",
        f"At m=12, M=1638 the full {N19_DRAWS} draws would need "
        f"{12 * 1638 * 8 * N19_DRAWS / 1e9:.1f} GB if materialised at once.",
        "The generator MUST chunk over draws. This is a hard constraint, not",
        "a preference, and it is the same point the predeclaration's",
        "implementation_note makes about batching -- but about memory rather",
        "than speed.",
        "",
    ]

    Path("results/final").mkdir(parents=True, exist_ok=True)
    Path(OUT).write_text("\n".join(L), encoding="utf-8")

    # machine-readable twin of the Measured table. Same numbers, tiny, so it is
    # committed alongside the md -- a plot should never have to re-run an hour
    # of measurement to redraw an axis.
    csv = ["m,cond,N,seconds,iters,ms_per_iter,converged"]
    csv += [
        f"{m},{cond:g},{n},{secs:.6f},{iters},{per_iter * 1e3:.6f},{int(ok)}"
        for m, cond, n, secs, iters, per_iter, ok in rows
    ]
    Path(OUT_CSV).write_text("\n".join(csv) + "\n", encoding="utf-8")
    print("\n" + "\n".join(L[-14:]))
    print(f"\nwritten -> {OUT}")
    print(f"written -> {OUT_CSV}")


if __name__ == "__main__":
    main()
