"""B1.1 tolerance calibration.

Measures achievable precision for the SPD primitive identities on THIS
machine's BLAS, and writes a dated record to results/final/.

This is a MEASUREMENT, not a test. It has no pass/fail and no assertions:
a test answers "is it correct", this answers "how correct can it be here".
It is outcome-independent evidence in the sense of the N-18a calibration
block in config/predeclaration.yaml -- it makes no reference to any result
we would like to obtain, so setting tolerances from it is legitimate.

Run after any change to numpy, the BLAS, or the primitives:
    python experiments/calibrate_spd.py
"""

import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

# pyproject's pythonpath=["py"] applies to pytest only; scripts need it too.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "py"))

from rfd.dgp.spd import random_spd
from rfd.spd.linalg import spd_sqrt, spd_invsqrt, spd_log, spd_exp, g_mean

SEED = 20260816
MS = [2, 3, 12]
CONDS = [1e1, 1e3, 1e5]
N = 200
EPS = np.finfo(np.float64).eps
OUT = "results/final/spd_calibration.md"


def rel_fro(X, ref):
    return np.linalg.norm(X - ref, axis=(-2, -1)) / np.linalg.norm(ref, axis=(-2, -1))


def measure(m, cond):
    """Returns {identity: (max relative residual, amplification exponent)}."""
    rng = np.random.default_rng(SEED)
    S = random_spd(rng, m=m, cond=cond, n=N)
    R, Ri = spd_sqrt(S), spd_invsqrt(S)
    X = random_spd(rng, m=m, cond=cond, n=N)
    Y = random_spd(rng, m=m, cond=cond, n=N)
    return {
        "exp(log S) = S": (rel_fro(spd_exp(spd_log(S)), S).max(), cond),
        "R R = S": (rel_fro(R @ R, S).max(), cond),
        "Ri S Ri = I": (rel_fro(Ri @ S @ Ri, np.eye(m)).max(), cond),
        "X # Y = Y # X": (rel_fro(g_mean(X, Y), g_mean(Y, X)).max(), cond ** 2),
    }


def main():
    rows, worst = [], {}
    for cond in CONDS:
        for m in MS:
            for name, (res, amp) in measure(m, cond).items():
                c = res / (EPS * amp)          # implied constant
                rows.append((name, m, cond, res, amp, c))
                worst[name] = max(worst.get(name, 0.0), c)

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# SPD primitive tolerance calibration",
        "",
        "Generated by `experiments/calibrate_spd.py`. Do not hand-edit --",
        "re-run instead, and keep superseded runs as dated sections.",
        "",
        f"- generated: {stamp}",
        f"- seed: {SEED}, n per cell: {N}",
        f"- numpy {np.__version__}, python {platform.python_version()}",
        f"- machine: {platform.processor() or 'unknown'} / {platform.platform()}",
        f"- eps: {EPS:.6e}",
        "",
        "`c` is the implied constant in  rel_residual = c * eps * amplification.",
        "`num_tol(safety=...)` must exceed max(c) with headroom.",
        "",
        "| identity | m | cond | rel residual | amplification | c |",
        "|---|---|---|---|---|---|",
    ]
    for name, m, cond, res, amp, c in rows:
        lines.append(f"| `{name}` | {m} | {cond:.0e} | {res:.3e} | {amp:.0e} | {c:.2e} |")

    lines += ["", "## Implied constants (max over the grid)", ""]
    lines += ["| identity | max c | safety needed |", "|---|---|---|"]
    for name, c in worst.items():
        lines.append(f"| `{name}` | {c:.2e} | {10 ** np.ceil(np.log10(max(c, 1))):.0f} |")
    lines += [
        "",
        f"**Suggested `safety` for all identities: "
        f"{10 ** np.ceil(np.log10(max(worst.values()))):.0f}**",
        "",
        "Note: g_mean is NOT measured at cond=1e8. There eps*kappa**2 ~ 1, the",
        "intermediate goes numerically indefinite, and spd_sqrt's strict guard",
        "raises. That ceiling is a real constraint on AIRM work (B1.3), not a",
        "calibration failure.",
        "",
    ]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines[-8:]))
    print(f"\nwritten -> {OUT}")


if __name__ == "__main__":
    main()
